// Generates real snarkjs proofs used by the Rust tests (§8.5: the on-chain
// verifier must pass against a real fixture before anything is built on top).
//
// Writes circuits/test/fixture.json and contracts/cpcv_note/src/test_fixture.rs.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { StrKey } from "@stellar/stellar-sdk";
import {
  agentField,
  attestAndProve,
  attesterPublicKey,
  formatVk,
  nullifierSecretCommitment,
  toHex32,
  type CpcvRecord,
  type SnarkjsVk,
} from "../../packages/zk/src/index.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const zk = resolve(root, "apps/web/zk");
const artifacts = {
  wasmPath: resolve(zk, "cpcv_attestation.wasm"),
  zkeyPath: resolve(zk, "cpcv_attestation_final.zkey"),
  vkPath: resolve(zk, "verification_key.json"),
};

const sha = (s: string) => createHash("sha256").update(s).digest();

// Deterministic test-only keys (never used on testnet).
export const TEST_ATTESTER_PRIV = sha("explorador advance TEST attester key").toString("hex");
export const TEST_NULLIFIER_SECRET = BigInt("0x" + sha("explorador advance TEST nullifier secret").subarray(0, 31).toString("hex"));
export const AGENT = StrKey.encodeContract(sha("fixture agent smart account"));
export const OTHER = StrKey.encodeContract(sha("fixture other account"));

export const DEAL_1: CpcvRecord = {
  buyerNif: 245_678_901,
  sellerNif: 198_765_432,
  salePriceCents: 30_000_000n, // €300,000
  commissionRateBps: 500,
  propertyAddress: "Rua Augusta 100, 3.º Esq, 1100-053 Lisboa",
  cpcvDay: 20_000,
  escrituraDay: 20_090,
};

export const DEAL_2: CpcvRecord = {
  buyerNif: 212_345_678,
  sellerNif: 287_654_321,
  salePriceCents: 18_500_000n, // €185,000
  commissionRateBps: 400,
  propertyAddress: "Rua de Santa Catarina 250, 4000-447 Porto",
  cpcvDay: 20_010,
  escrituraDay: 20_070,
};

async function main() {
  const keys = { attesterPrivHex: TEST_ATTESTER_PRIV, nullifierSecret: TEST_NULLIFIER_SECRET };
  const p1 = await attestAndProve(DEAL_1, AGENT, keys, artifacts, { salt: 111_111n });
  // Same deal re-attested with a new salt: same nullifier, different commitment.
  const p1b = await attestAndProve(DEAL_1, AGENT, keys, artifacts, { salt: 222_222n });
  const p2 = await attestAndProve(DEAL_2, AGENT, keys, artifacts, { salt: 333_333n });
  if (p1.publicSignals.nullifier !== p1b.publicSignals.nullifier) throw new Error("nullifier should not depend on salt");

  const vk = formatVk(JSON.parse(readFileSync(artifacts.vkPath, "utf8")) as SnarkjsVk);
  const pub = await attesterPublicKey(TEST_ATTESTER_PRIV);
  const nsc = await nullifierSecretCommitment(TEST_NULLIFIER_SECRET);

  const proofOut = (p: typeof p1) => ({
    soroban: p.soroban,
    snarkjs: p.proof,
    publicSignals: p.publicSignalsList,
    totalCommissionCents: p.publicSignals.totalCommissionCents.toString(),
    escrituraDay: p.publicSignals.escrituraDay,
    commitment: toHex32(p.publicSignals.commitment),
    nullifier: toHex32(p.publicSignals.nullifier),
  });

  const fixture = {
    agent: AGENT,
    other: OTHER,
    agentField: toHex32(agentField(AGENT)),
    attesterAx: toHex32(pub.ax),
    attesterAy: toHex32(pub.ay),
    nullifierSecretCommitment: toHex32(nsc),
    vk,
    deal1: proofOut(p1),
    deal1b: proofOut(p1b),
    deal2: proofOut(p2),
  };
  writeFileSync(resolve(here, "fixture.json"), JSON.stringify(fixture, null, 2) + "\n");

  const rsProof = (name: string, p: ReturnType<typeof proofOut>) => `
pub mod ${name} {
    pub const A: &str = "${p.soroban.a}";
    pub const B: &str = "${p.soroban.b}";
    pub const C: &str = "${p.soroban.c}";
    pub const TOTAL_COMMISSION_CENTS: u64 = ${p.totalCommissionCents};
    pub const ESCRITURA_DAY: u32 = ${p.escrituraDay};
    pub const COMMITMENT: &str = "${p.commitment}";
    pub const NULLIFIER: &str = "${p.nullifier}";
}
`;

  const rs = `// @generated by circuits/test/make-fixture.ts — do not edit.
// Real snarkjs Groth16 proofs over the committed circuit and zkey.
#![allow(dead_code)]

pub const AGENT: &str = "${AGENT}";
pub const OTHER: &str = "${OTHER}";
pub const AGENT_FIELD: &str = "${fixture.agentField}";
pub const ATTESTER_AX: &str = "${fixture.attesterAx}";
pub const ATTESTER_AY: &str = "${fixture.attesterAy}";
pub const NULLIFIER_SECRET_COMMITMENT: &str = "${fixture.nullifierSecretCommitment}";

pub const VK_ALPHA: &str = "${vk.alpha}";
pub const VK_BETA: &str = "${vk.beta}";
pub const VK_GAMMA: &str = "${vk.gamma}";
pub const VK_DELTA: &str = "${vk.delta}";
pub const VK_IC: [&str; ${vk.ic.length}] = [
${vk.ic.map((x) => `    "${x}",`).join("\n")}
];
${rsProof("deal1", fixture.deal1)}${rsProof("deal1b", fixture.deal1b)}${rsProof("deal2", fixture.deal2)}`;
  writeFileSync(resolve(root, "contracts/cpcv_note/src/test_fixture.rs"), rs);
  console.log("wrote circuits/test/fixture.json and contracts/cpcv_note/src/test_fixture.rs");
  process.exit(0);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
