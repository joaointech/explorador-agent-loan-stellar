// `pnpm keys:generate` (§11.1): role keypairs (Friendbot-funded), attester key and secrets → apps/web/.env.local.
// Existing values are kept, so re-running only fills what is missing. Keys are testnet-only.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { Keypair } from "@stellar/stellar-sdk";
import { FR } from "@advance/zk";
import { friendbot } from "@/lib/stellar/network";

const DEFAULTS: [string, string][] = [
  ["DATABASE_URL", "postgresql://advance:advance@localhost:5433/advance"],
  ["APP_URL", "http://localhost:3000"],
  ["ADMIN_EMAILS", "admin@explorador.pt"],
  ["EMAIL_FROM", '"explorador advance <advance@explorador.pt>"'],
  ["WEBAUTHN_RP_ID", "localhost"],
  ["WEBAUTHN_RP_NAME", '"explorador advance"'],
  ["STELLAR_NETWORK", "testnet"],
  ["STELLAR_RPC_URL", "https://soroban-testnet.stellar.org"],
  ["STELLAR_NETWORK_PASSPHRASE", '"Test SDF Network ; September 2015"'],
  ["DEMO_MODE", "true"],
  ["RESEND_API_KEY", ""],
  ["LITHIC_API_KEY", ""],
  ["LITHIC_ASA_HMAC_SECRET", ""],
];

function parseEnv(text: string): Map<string, string> {
  const m = new Map<string, string>();
  for (const line of text.split("\n")) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (match) m.set(match[1], match[2]);
  }
  return m;
}

/** Random field element below the BN254 scalar modulus (31 bytes). */
function fieldSecret(): string {
  let v: bigint;
  do v = BigInt("0x" + randomBytes(31).toString("hex"));
  while (v >= FR || v === 0n);
  return v.toString(16).padStart(62, "0");
}

export async function generateKeys(webRoot: string, log: (l: string) => void = console.log) {
  const file = path.join(webRoot, ".env.local");
  const existing = existsSync(file) ? parseEnv(readFileSync(file, "utf8")) : new Map<string, string>();
  const out = new Map(existing);
  const setIfMissing = (k: string, make: () => string) => {
    if (!out.get(k)) {
      out.set(k, make());
      log(`generated ${k}`);
    }
  };

  for (const [k, v] of DEFAULTS) if (!out.has(k)) out.set(k, v);
  setIfMissing("SESSION_SECRET", () => randomBytes(32).toString("hex"));
  setIfMissing("CRON_SECRET", () => randomBytes(16).toString("hex"));
  for (const role of ["ADMIN", "OPERATOR", "TREASURY", "SPONSOR"]) setIfMissing(`${role}_SECRET`, () => Keypair.random().secret());
  setIfMissing("CARD_SETTLEMENT_PUBLIC", () => Keypair.random().publicKey());
  setIfMissing("ATTESTER_EDDSA_PRIVKEY", () => randomBytes(32).toString("hex"));
  setIfMissing("NULLIFIER_SECRET", fieldSecret);
  setIfMissing("PII_ENCRYPTION_KEY", () => randomBytes(32).toString("hex"));

  const order = [
    "DATABASE_URL", "APP_URL", "SESSION_SECRET", "CRON_SECRET", "ADMIN_EMAILS", "RESEND_API_KEY", "EMAIL_FROM", "WEBAUTHN_RP_ID", "WEBAUTHN_RP_NAME",
    "STELLAR_NETWORK", "STELLAR_RPC_URL", "STELLAR_NETWORK_PASSPHRASE", "ADMIN_SECRET", "OPERATOR_SECRET", "TREASURY_SECRET", "CARD_SETTLEMENT_PUBLIC",
    "SPONSOR_SECRET", "DEMO_MODE", "ATTESTER_EDDSA_PRIVKEY", "NULLIFIER_SECRET", "PII_ENCRYPTION_KEY", "LITHIC_API_KEY", "LITHIC_ASA_HMAC_SECRET",
  ];
  const keys = [...order, ...[...out.keys()].filter((k) => !order.includes(k))];
  const body = keys.filter((k) => out.has(k)).map((k) => `${k}=${out.get(k)}`).join("\n");
  writeFileSync(file, `# Generated by pnpm keys:generate — TESTNET ONLY, never reuse these keys.\n${body}\n`, { mode: 0o600 });
  log(`wrote ${file}`);

  const accounts = [
    ...["ADMIN", "OPERATOR", "TREASURY", "SPONSOR"].map((r) => [r, Keypair.fromSecret(out.get(`${r}_SECRET`)!).publicKey()] as const),
    ["CARD_SETTLEMENT", out.get("CARD_SETTLEMENT_PUBLIC")!] as const,
  ];
  for (const [role, pub] of accounts) {
    await friendbot(pub);
    log(`funded ${role.toLowerCase()} ${pub}`);
  }
}
