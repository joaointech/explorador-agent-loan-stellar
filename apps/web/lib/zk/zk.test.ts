describe("snarkjs ⇄ Soroban formatting (spec §8.5)", () => {
  const vk = loadVerificationKey();

  it("encodes G2 imaginary part first (EIP-197): gamma is the BN254 G2 generator", () => {
    expect(toHex(vkToSoroban(vk).gamma)).toBe(
      "198e9393920d483a7260bfb731fb5d25f1aa493335a9e71297e485b7aef312c2" +
        "1800deef121f1e76426a00665e5c4479674322d4f75edadd46debd5cd992f6ed" +
        "090689d0585ff075ec9e99ad690c3395bc4b313370b38ef355acdadcd122975b" +
        "12c85ea5db8c6deb4aab71808dcb408fe3d1e7690c43d37b4ce6cc0166fa7daa",
    );
  });

  it("round-trips every verification key point", () => {
    const s = vkToSoroban(vk);
    expect(g1FromBytes(s.alpha)).toEqual(vk.vk_alpha_1);
    for (const [bytes, point] of [
      [s.beta, vk.vk_beta_2],
      [s.gamma, vk.vk_gamma_2],
      [s.delta, vk.vk_delta_2],
    ] as const) {
      expect(g2FromBytes(bytes)).toEqual(point);
    }
    expect(s.ic).toHaveLength(10);
    s.ic.forEach((p, i) => expect(g1FromBytes(p)).toEqual(vk.IC[i]));
    expect(vkFromSorobanHex(vkToSorobanHex(vk))).toEqual(s);
  });

  it("matches the committed verification_key.soroban.json (deploy input)", () => {
    const committed = JSON.parse(readFileSync(path.join(zkArtifacts().dir, "verification_key.soroban.json"), "utf8"));
    expect(committed).toEqual(vkToSorobanHex(vk));
  });

  it("negates G1 as (x, p − y), is self-inverse and keeps infinity", () => {
    const a = g1ToBytes(vk.vk_alpha_1);
    const neg = negateG1(a);
    expect(toHex(neg.subarray(0, 32))).toBe(toHex(a.subarray(0, 32)));
    expect(bytesToBigInt(neg.subarray(32))).toBe(FIELD_P - BigInt(vk.vk_alpha_1[1]));
    expect(negateG1(neg)).toEqual(a);
    expect(negateG1(new Uint8Array(64))).toEqual(new Uint8Array(64));
    expect(g1ToBytes(["0", "1", "0"])).toEqual(new Uint8Array(64));
    expect(g1FromBytes(new Uint8Array(64))).toEqual(["0", "1", "0"]);
  });

  it("rejects malformed points", () => {
    expect(() => g1ToBytes([FIELD_P.toString(), "1", "1"])).toThrow(/base-field/);
    expect(() => g1ToBytes(["1", "2", "3"])).toThrow(/affine/);
    expect(() => g1FromBytes(new Uint8Array(63))).toThrow();
    expect(() => g2ToBytes([["1", "2"], ["3", "4"], ["2", "0"]])).toThrow(/affine/);
    expect(() => g2FromBytes(new Uint8Array(64))).toThrow();
  });
});

describe("keys (pnpm keys:generate, deploy)", () => {
  it("derives the TEST attester public key and nullifier-secret commitment", async () => {
    // Independent values: circomlibjs via circuits/test/helpers.mjs.
    const pub = await attesterPublicKey(TEST_KEYS.attesterPrivKey);
    expect(pub.axHex).toBe("11be77cc7c3f4e6937c5d8b8cdc8d8a64b044b8bc8816346c38e018c7459013b");
    expect(pub.ayHex).toBe("1359b76727b5d50085aaec4ce40190ab5e3673d14877e57c54d5bac652029a33");
    expect(toHex(await nullifierSecretCommitment(TEST_KEYS.nullifierSecret))).toBe(
      "1f72848892f676a244a763a69cae69a23776ceaa35e0cdfeb96c7ae3384a7227",
    );
  });

  it("generates well-formed secrets", async () => {
    const key = generateAttesterKey();
    expect(key).toMatch(/^[0-9a-f]{64}$/);
    expect(parseAttesterKey(key)).toHaveLength(32);
    expect((await attesterPublicKey(key)).ax).toHaveLength(32);
    const secret = generateNullifierSecret();
    expect(BigInt(secret)).toBeLessThan(1n << 248n);
    expect(parseNullifierSecret(secret)).toBe(BigInt(secret));
    expect(parseNullifierSecret("0x" + "0e".repeat(31))).toBe(BigInt(TEST_KEYS.nullifierSecret));
    expect(() => parseNullifierSecret(FIELD_R.toString())).toThrow();
    expect(() => parseAttesterKey("abcd")).toThrow(/32 bytes/);
  });
});

describe("attestation inputs", () => {
  it("keeps the nullifier independent of the salt", async () => {
    const a = await buildCpcvWitnessInput(AGENT_A, DEAL, TEST_KEYS, { salt: 1n });
    const b = await buildCpcvWitnessInput(AGENT_A, DEAL, TEST_KEYS, { salt: 2n });
    expect(a.nullifier).toBe(b.nullifier);
    expect(a.commitment).not.toBe(b.commitment);
    expect(a.totalCommissionCents).toBe(1_500_000n);
    expect(a.agentCommissionCents).toBe(750_000n);
  });

  it.each([
    ["an 8-digit buyer NIF", { buyerNif: "12345678" }, "INVALID_NIF"],
    ["a non-numeric seller NIF", { sellerNif: "12345678a" }, "INVALID_NIF"],
    ["a 0.99% rate", { commissionRateBps: 99 }, "INVALID_RATE"],
    ["a 10.01% rate", { commissionRateBps: 1001 }, "INVALID_RATE"],
    ["a fractional rate", { commissionRateBps: 4.5 }, "INVALID_RATE"],
    ["a zero price", { salePriceCents: 0n }, "INVALID_PRICE"],
    ["a price of 2^64 cents", { salePriceCents: 1n << 64n }, "INVALID_PRICE"],
    ["an escritura on the CPCV day", { escrituraDay: DEAL.cpcvDay }, "INVALID_DATE"],
    ["a negative CPCV day", { cpcvDay: -1 }, "INVALID_DATE"],
    ["a blank address", { propertyAddress: "  " }, "INVALID_ADDRESS"],
    ["a 300-byte address", { propertyAddress: "x".repeat(300) }, "INVALID_ADDRESS"],
  ] as [string, Partial<CpcvPrivateInput>, string][])("rejects %s (%s)", async (_label, patch, code) => {
    const err = await buildCpcvWitnessInput(AGENT_A, { ...DEAL, ...patch }, TEST_KEYS).catch((e: unknown) => e);
    expect(err).toBeInstanceOf(CpcvInputError);
    expect((err as CpcvInputError).code).toBe(code);
  });

  it("rejects an invalid agent address", async () => {
    await expect(buildCpcvWitnessInput("GABC", DEAL, TEST_KEYS)).rejects.toMatchObject({ code: "INVALID_AGENT" });
  });
});

describe("proveCpcv (spec §8.6)", () => {
  it("proves, verifies locally and formats for Soroban within the 60 s route budget", { timeout: 60_000 }, async () => {
    process.env.ATTESTER_EDDSA_PRIVKEY = TEST_KEYS.attesterPrivKey;
    process.env.NULLIFIER_SECRET = TEST_KEYS.nullifierSecret;

    const steps: ProveStep[] = [];
    const started = performance.now();
    const p = await proveCpcv(AGENT_A, DEAL, (s) => steps.push(s));
    const ms = Math.round(performance.now() - started);
    console.log(`proveCpcv: ${ms} ms (first proof in this process: includes wasm/zkey load and curve init)`);
    expect(ms).toBeLessThan(60_000);
    expect(steps).toEqual(["signing", "proving", "verifying"]);

    // Amounts and public signals in circuit order (spec §8.2).
    expect(p.totalCommissionCents).toBe(1_500_000n);
    expect(p.agentCommissionCents).toBe(750_000n);
    const params = await attesterParams(TEST_KEYS);
    expect(p.publicSignals).toEqual(
      [
        agentFieldValue(AGENT_A),
        1_500_000n,
        750_000n,
        20841n,
        bytesToBigInt(p.commitment),
        bytesToBigInt(p.nullifier),
        bytesToBigInt(params.attesterAx),
        bytesToBigInt(params.attesterAy),
        bytesToBigInt(params.nullifierSecretCommitment),
      ].map(String),
    );
    expect(p.commitment).toHaveLength(32);
    expect(p.salt).toMatch(/^[0-9a-f]{64}$/);

    // A is negated on the Soroban side; un-negating gives the snarkjs proof back.
    expect(p.sorobanProof.a).toHaveLength(64);
    expect(p.sorobanProof.b).toHaveLength(128);
    expect(p.sorobanProof.c).toHaveLength(64);
    expect(toHex(p.sorobanProof.a)).not.toBe(toHex(g1ToBytes(p.snarkjsProof.pi_a)));
    expect(negateG1(p.sorobanProof.a)).toEqual(g1ToBytes(p.snarkjsProof.pi_a));
    expect(sorobanToProof(p.sorobanProof)).toEqual(p.snarkjsProof);
    expect(sorobanToProof(proofToHex(p.sorobanProof))).toEqual(p.snarkjsProof);
    expect(proofToSoroban(sorobanToProof(p.sorobanProof))).toEqual(p.sorobanProof);
    expect(proofFromHex(proofToHex(p.sorobanProof))).toEqual(p.sorobanProof);

    // The registry flow: rebuild the public signals from on-chain data and re-verify.
    const onChain = {
      agent: AGENT_A,
      totalCommission: 1_500_000n * 100_000n,
      agentCommission: 750_000n * 100_000n,
      escrituraDay: DEAL.escrituraDay,
      commitment: fieldToHex(bytesToBigInt(p.commitment)),
      nullifier: p.nullifier,
      proof: proofToHex(p.sorobanProof),
    };
    expect(buildPublicSignals(onChain, params)).toEqual(p.publicSignals);
    const check = await verifyNoteProof(onChain, params, loadVerificationKey());
    expect(check.valid).toBe(true);
    expect(check.snarkjsProof).toEqual(p.snarkjsProof);
    const tampered = await verifyNoteProof({ ...onChain, totalCommission: onChain.totalCommission + 100_000n }, params, loadVerificationKey());
    expect(tampered.valid).toBe(false);
    expect(() => buildPublicSignals({ ...onChain, totalCommission: 1n }, params)).toThrow(/whole number of cents/);
  });

  it("encodes field elements as 32-byte big-endian", () => {
    expect(toHex(bigIntToBytes(1n))).toBe("00".repeat(31) + "01");
    expect(bytesToBigInt(fromHex("0x" + "00".repeat(31) + "ff"))).toBe(255n);
    expect(() => fieldToHex(FIELD_R)).toThrow();
  });
});
